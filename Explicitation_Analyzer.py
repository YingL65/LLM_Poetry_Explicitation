import matplotlib.pyplot as plt
import pandas as pd
import numpy as np
import re
import nltk
from nltk.corpus import stopwords

# 1. Configuration & Setup
nltk.download('stopwords', quiet=True)
stop_words = set(stopwords.words('english'))

data = []

# 2. Data Collection
# Group 1: Standard Mode
for i in range(3):
    name = input(f"Standard Model {i+1} Name: ") or f"Standard_{i+1}"
    text = input(f"Text: ")
    data.append({"Model": name, "Mode": "Standard", "Text": text})

# Group 2: Thinking Mode
for i in range(3):
    name = input(f"Thinking Model {i+1} Name: ") or f"Thinking_{i+1}"
    text = input(f"Text: ")
    data.append({"Model": name, "Mode": "Thinking", "Text": text})

# 3. Analysis Logic
def analyze_text(text):
    # Replace punctuation with space to avoid word fusion (e.g., "end.The")
    clean_text = re.sub(r'[^\w\s]', ' ', text.lower())
    words = clean_text.split()

    total_wc = len(words)
    sw_count = sum(1 for w in words if w in stop_words)
    density = (sw_count / total_wc) if total_wc > 0 else 0

    return total_wc, sw_count, density

results = []
for item in data:
    wc, sw, den = analyze_text(item['Text'])
    results.append({
        "Model": item['Model'],

        "Mode": item['Mode'],
        "Word Count": wc,
        "Stopwords": sw,
        "Density": den
    })

df = pd.DataFrame(results)
print(df)
